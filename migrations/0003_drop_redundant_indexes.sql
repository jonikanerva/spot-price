-- Drop three indexes that duplicate other indexes (#128). No query needs
-- them, and each one costs disk, cache memory, and write work.
--
-- - idx_fingrid_actuals_dataset_start has the columns and the order of the
--   primary key of fingrid_actuals (dataset_id, start_time).
-- - idx_api_keys_user_id duplicates the unique index
--   idx_api_keys_single_per_user on the same column.
-- - idx_fingrid_forecasts_issued (issued_at) served only the vintage prune.
--   On PostgreSQL 18 the prune uses the primary key
--   (dataset_id, issued_at, start_time) with a btree skip scan, because
--   dataset_id has only two values.
--
-- SQLx runs this file in a transaction, so DROP INDEX CONCURRENTLY is not
-- possible. The tables are small, and the lock is short. The TypeScript
-- revert path needs none of these indexes. Do not edit this file after
-- release: SQLx checks its hash.
DROP INDEX IF EXISTS idx_fingrid_actuals_dataset_start;
DROP INDEX IF EXISTS idx_api_keys_user_id;
DROP INDEX IF EXISTS idx_fingrid_forecasts_issued;
